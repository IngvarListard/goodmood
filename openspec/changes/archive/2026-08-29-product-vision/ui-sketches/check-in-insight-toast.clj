;; UI-скетч: toast/alert подсказки инсайта после сохранения записи (Фаза 4)
;; Источник: design.md Decision 14.5 (OOB-toast на /feed после отправки записи).
;; Этот файл — референс для имплементационного change `add-coping-channels`.
;; Не production-код, а фиксация UX-дизайна.

;; ──────────────────────────────────────────────────────────────
;; 1. Размещение и поток
;; ──────────────────────────────────────────────────────────────
;; После успешной отправки /check-in сохраняется существующий редирект на
;; /feed (см. views/check_in.clj, htmx:afterRequest). Релевантный инсайт для
;; только что введённого state_label возвращается в том же ответе через
;; hx-swap-oob="true" и всплывает как dismissible-toast на /feed.
;; Non-blocking: не прерывает flow, не modal.
;;
;; Случай «нет инсайта» — toast НЕ показывается. Онбординг здесь не к месту
;; (он живёт в виджете /feed-insights, рядом с hero). Проверка на сервере:
;; (when insight (toast ...)).

;; ──────────────────────────────────────────────────────────────
;; 2. Toast (OOB-фрагмент, рендерится в ответ POST /entries)
;; ──────────────────────────────────────────────────────────────
;; Вставляется в #feed-toasts (контейнер на /feed). hx-swap-oob="true"
;; кладёт фрагмент в указанный элемент без перерисовки остальной страницы.
;; Параметры (в имплементации):
;;   insight — релевантный инсайт (:id, :context, :advice-to-self) или nil.

