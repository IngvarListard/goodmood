;; ──────────────────────────────────────────────────────────────
;; 4. Заметки по UX
;; ──────────────────────────────────────────────────────────────
;; - alert-info, а не success/error: похвала и тревога здесь не к месту,
;;   инсайт — нейтральная поддержка. Спокойный тон, не стимулирует.
;; - Контент: context (1 строка) + первый advice. Не «все советы» — минимум
;;   когнитивной нагрузки. Полный — по ссылке /insights/:id.
;; - Заголовок: «В таком состоянии тебе помогало:» — поддерживающий,
;;   возвращает пользователю его же слова, без «система рекомендует».
;; - Dismiss: крестик (btn-ghost), hyperscript add .hidden. Non-modal.
;; - Touch-target: кнопка × — h-11 min-h-11 (44px). Карточка не кликабельна
;;   целиком (не плодить случайные переходы из toast), ссылка — отдельная.
;; - На мобилке: fixed bottom-4 right-4, над FAB. Не перекрывает критичное.
;; - Нет инсайта → фрагмент не рендерится (сервер проверяет), без пустых
;;   мест, без онбординга.

;; ──────────────────────────────────────────────────────────────
;; 5. Touch-targets
;; ──────────────────────────────────────────────────────────────
;; - Кнопка × : h-11 min-h-11 (44px).
;; - Ссылка «посмотреть полностью» — text link, не требует 44px (не первичное
;;   действие; карточка читается, а не нажимается).
;; - Вся карточка НЕ кликабельна — единственное действие = закрыть/перейти
;;   по явной ссылке (меньше случайных переходов при «голова не соображает»).