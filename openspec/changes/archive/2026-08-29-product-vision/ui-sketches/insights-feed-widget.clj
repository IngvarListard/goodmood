;; ──────────────────────────────────────────────────────────────
;; 3. Карточка инсайта — компактный вариант для /feed
;; ──────────────────────────────────────────────────────────────
;; В имплементации: (defn insight-compact-card [insight] ...)
;; Параметризуется: :id, :category, :context, :first-advice,
;;                  :extra-advice-count, :created-at.
;; Локализация: бейдж категории через i18n/t.
;; ВСЯ карточка — ссылка (<a>), кликабельная целиком → /insights/:id.
;; Кнопка «записать инсайт» — снаружи карточки (в секции, не внутри <a>),
;; чтобы не ломать семантику nested-interactives.

;; ──────────────────────────────────────────────────────────────
;; 4. Заметки по UX
;; ──────────────────────────────────────────────────────────────
;; - Размещение: под hero-карточкой, ДО compact-cards остальных записей.
;;   Обоснование: инсайт — ядро продуктовой ценности (Decision 3), его место
;;   рядом с текущим состоянием, а не внизу ленты.
;; - Заголовок секции: «Что ты сам говорил в таком состоянии» —
;;   поддерживающий, не «Инсайты для тревоги» (клинический тон).
;;   Уровень заголовка h2 — как у «Сегодня» (today-section), но
;;   opacity-60, чтобы не конкурировать с hero.
;; - Карточки: 1 (Decision 13.4). 2 — опционально (константа +max-on-feed+).
;;   Компактнее, чем на /insights: p-3 (вместо p-4), line-clamp-1.
;; - Карточка целиком — <a href="/insights/:id">. Клик → полная карточка.
;;   НЕ htmx-свап, а полная навигация — пользователь хочет весь инсайт.
;; - advice: первый пункт виден, остальные — «…ещё N» (кнопка-текст,
;;   не отдельная кнопка — клик по карточке уже ведёт к полному).
;; - Кнопка «записать инсайт» — снаружи карточек, в секции. btn-ghost,
;;   не primary (не давим). state_label из текущей записи — query param.
;; - Онбординг (OQ3): «Инсайтов для состояния "тревога" ещё нет» + кнопка.
;;   НЕ «у тебя нет инсайтов» (может быть, что для других состояний есть —
;;   тогда текст вводит в заблуждение). Уточнение по состоянию = уважение.
;; - Нет релевантных, но есть инсайты для других состояний:
;;   тот же онбординг. Система не хвастается наличием — только предлагает.
;; - Бейдж категории: badge-xs (мини), не отвлекает от контекста.
;; - Дата: мелкая, opacity-50, справа — не привлекающая внимания.

;; ──────────────────────────────────────────────────────────────
;; 5. Цветовая логика
;; ──────────────────────────────────────────────────────────────
;; - Карточки: bg-base-200 shadow-sm (как compact-card в feed.clj).
;;   hover:shadow-md — лёгкая обратная связь на десктопе.
;; - Бейдж категории: badge-secondary badge-xs — спокойный.
;; - Онбординг: текст opacity-70, кнопка btn-primary (единственный
;;   «якорь» в пустом состоянии — должна быть заметной).
;; - Кнопка «записать инсайт»: btn-ghost — не конкурирует с FAB «+»
;;   и hero-кнопками.

;; ──────────────────────────────────────────────────────────────
;; 6. Touch-targets
;; ──────────────────────────────────────────────────────────────
;; - Карточка целиком кликабельна — площадь touch = вся карточка.
;; - Кнопка «записать инсайт»: h-11 min-h-11 (44px).
;; - Онбординг-кнопка: h-11 min-h-11.
;; - Бейджи не интерактивны — не нуждаются в touch-target.

;; ──────────────────────────────────────────────────────────────
;; 7. Структура в today-section (контекст /feed)
;; ──────────────────────────────────────────────────────────────
;;
;;   ┌─ today-section ──────────────────────────────────┐
;;   │  ┌─ hero-card (latest entry) ──────────────────┐  │
;;   │  │ 🌹 rose │ label │ axes │ note               │  │
;;   │  └─────────────────────────────────────────────┘  │
;;   │  ┌─ feed-insight-widget ──────────────────────┐  │  ← ЭТОТ СКЕТЧ
