;; UI-скетч: предложение мягкого режима на /check-in (Фаза 4)
;; Источник: design.md Decision 14.4 (soft mode в плохом состоянии).
;; Этот файл — референс для имплементационного change `add-coping-channels`.
;; Не production-код, а фиксация UX-дизайна.

;; ──────────────────────────────────────────────────────────────
;; 1. Триггер показа
;; ──────────────────────────────────────────────────────────────
;; Баннер рендерится сверху формы /check-in, если последняя запись
;; пользователя имеет state_label "low" или "mixed". В остальных состояниях
;; баннер не рендерится (никаких пустых мест).
;;
;; Оба выбора — равноправные кнопки. Мягкий режим опционален и не
;; принуждает: при low/mixed это рекомендация, не блокировка. Кнопка
;; «полная форма» всегда рядом, чтобы пользователь не чувствовал себя
;; запертым в упрощении.

;; ──────────────────────────────────────────────────────────────
;; 2. Баннер-предложение
;; ──────────────────────────────────────────────────────────────
;; Параметры (в имплементации):
;;   — корневой элемент-контейнер — НАД формой /check-in;
;;   — интерактивность: hyperscript скрывает energy/anxiety и опциональные
;;     блоки, оставляя только mood_score (без reload, без JS-файла).
;;
;; Переключение работает так:
;;   click «мягкий режим»  -> hide #soft-targets, show #mood-only
;;   click «полная форма»  -> показать всё (default-состояние)

(def soft-mode-banner
  [:div {:class "alert alert-info shadow-sm mb-4" :id "soft-mode-banner"}
   [:div {:class "flex items-start gap-3 w-full"}
    [:svg {:xmlns "http://www.w3.org/2000/svg"
           :width 20 :height 20 :viewBox "0 0 24 24"
           :fill "none" :stroke "currentColor"
           :stroke-width 1.8 :stroke-linecap "round" :stroke-linejoin "round"}
     [:path {:d "M12 18v-5.25m0 0a6.01 6.01 0 0 0 1.5-.189m-1.5.189a6.01 6.01 0 0 1-1.5-.189m3.75 7.429a3.75 3.75 0 1 1-7.5 0V8.25M8.25 8.25a3.75 3.75 0 0 1 7.5 0"}]
     [:path {:d "M9 18h6"}]
     [:path {:d "M10 21h4"}]]

    [:div {:class "flex-1 min-w-0"}
     [:p {:class "text-sm font-medium"}
      "Тебе сейчас может быть непросто. Включить мягкий режим?"]
     [:p {:class "text-sm opacity-80 mt-1"}
      "Только настроение, без подробностей."]
     [:div {:class "flex gap-2 mt-2 flex-wrap"}
      [:button {:type "button"
                :class "btn btn-primary btn-sm h-11 min-h-11 px-4"
                :_ "on click
                      add .hidden to #soft-targets
                      remove .hidden from #mood-only
                      add .soft-on to me
                      remove .soft-on from #full-form-btn"}
       "мягкий режим"]
      [:button {:type "button"
                :id "full-form-btn"
                :class "btn btn-ghost btn-sm h-11 min-h-11 px-4"
                :_ "on click
                      remove .hidden from #soft-targets
                      add .hidden to #mood-only
                      remove .soft-on from #soft-mode-btn"}
       "полная форма"]]]]])

;; ──────────────────────────────────────────────────────────────
;; 3. Минимальный режим: только mood_score
;; ──────────────────────────────────────────────────────────────
;; Когда мягкий режим включён, показываем один слайдер настроения и
;; кнопку «сохранить». Остальное скрыто (energy/anxiety + optional).
;; Значение хранится в том же поле mood_score, что и в полной форме.

(def soft-mode-form-core
  [:div {:id "mood-only" :class "hidden"}
   [:div {:class "form-control"}
    [:div {:class "label px-0"}
     [:span {:class "label-text text-base font-medium"} "Настроение"]]
    [:input {:type "range" :name "mood_score" :min "0" :max "10" :value "5"
             :class "range range-primary"
             :style "height: 2rem"
             :_ "on input put my value into #mood-only-value"}]
    [:div {:class "flex justify-between mt-0.5 px-0.5"}
     [:span {:class "text-xs opacity-40"} "0"]
     [:span {:id "mood-only-value" :class "text-sm font-semibold tabular-nums"} "5"]
     [:span {:class "text-xs opacity-40"} "10"]]
    [:button {:type "submit" :class "btn btn-primary w-full h-12 mt-4"}
     "Сохранить"]]])

;; ──────────────────────────────────────────────────────────────
;; 4. Полная форма — скрытые target-элементы
;; ──────────────────────────────────────────────────────────────
;; Это то, что скрывается в мягком режиме: счётчики энергия/тревога и
;; все опциональные блоки. Разметка повторяет существующую форму /check-in,
;; но обёрнута в общий id, чтобы hyperscript мог скрыть одним действием.
(def full-form-targets
  [:div {:id "soft-targets"}
   [:div {:class "form-group"}
    [:p {:class "text-xs uppercase tracking-wide opacity-50"}
     "Подробности (опционально)"]]
   [:div {:class "form-group"}
    [:p {:class "text-xs uppercase tracking-wide opacity-40"}
     "Энергия и тревога"]]
   [:div {:class "form-group"}
    [:p {:class "text-xs uppercase tracking-wide opacity-40"}
     "Сон / Заметка / Активность"]]])

;; ──────────────────────────────────────────────────────────────
;; 5. Заметки по UX
;; ──────────────────────────────────────────────────────────────
;; - Размещение: САМЫЙ верх формы /check-in, до ядра (mood/energy/anxiety).
;;   Показывается только в low/mixed — мягкий тон в плохом состоянии.
;; - alert-info: нейтральная поддержка, не похвала и не тревога. Спокойная.
;; - Copy без вины: «Тебе сейчас может быть непросто» — поддерживающе,
;;   не «вы в депрессии», не «цепочка разорвана». Не strik/self-blame.
;; - Две равноправные кнопки: «мягкий режим» (primary — рекомендация) и
;;   «полная форма» (ghost — не давим, оставляем выбор).
;; - Мягкий режим: только mood_score. Не показывает energy/anxiety/focus и
;;   опциональные блоки — минимум нагрузки, акцент на фиксации состояния
;;   без обязательства описывать боль.
;; - Non-modal, non-blocking: не прерывает, если пользователь уже заполняет
;;   полную форму. Работает через hyperscript toggle, без сырого JS.
;; - Опциональные блоки в полной форме остаются явно skip-able (уже так в
;;   существующей форме check_in.clj).

;; ──────────────────────────────────────────────────────────────
;; 6. Touch-targets
;; ──────────────────────────────────────────────────────────────
;; - Кнопки «мягкий режим» / «полная форма»: h-11 min-h-11 (44px).
;; - Слайдер mood_score в мягком режиме: height 2rem (32px) + широкий
;;   touch (вся ширина формы) — достаточно при «голова не соображает».
;; - Кнопка «Сохранить»: h-12 (48px) — первичное действие.

